/// Request payload for text completion.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct CompletionRequest {
    pub prompt: String,
    pub brain: BrainType,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub max_tokens: Option<u32>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub temperature: Option<f32>,
    #[serde(default)]
    pub stream: bool,
}

impl CompletionRequest {
    pub fn new(prompt: impl Into<String>, brain: BrainType) -> Self {
        Self {
            prompt: prompt.into(),
            brain,
            max_tokens: None,
            temperature: None,
            stream: false,
        }
    }
}

/// Full response payload from text completion.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CompletionResponse {
    pub text: String,
    pub brain: BrainType,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tokens_generated: Option<u32>,
}

impl CompletionResponse {
    pub fn new(text: impl Into<String>, brain: BrainType) -> Self {
        Self {
            text: text.into(),
            brain,
            tokens_generated: None,
        }
    }
}

/// Single streaming chunk from token generation.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CompletionChunk {
    pub text: String,
    pub brain: BrainType,
    pub done: bool,
}

impl CompletionChunk {
    pub fn new(text: impl Into<String>, brain: BrainType, done: bool) -> Self {
        Self {
            text: text.into(),
            brain,
            done,
        }
    }
}

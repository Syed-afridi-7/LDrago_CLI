//! Core data transfer and session types for LDrago CLI.

use serde::{Deserialize, Serialize};

/// Specialized AI engine persona/architecture.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum BrainType {
    #[serde(alias = "Coding", alias = "CODING")]
    Coding,
    #[serde(alias = "Design", alias = "DESIGN")]
    Design,
    #[serde(alias = "General", alias = "GENERAL")]
    General,
}

impl std::fmt::Display for BrainType {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Coding => write!(f, "coding"),
            Self::Design => write!(f, "design"),
            Self::General => write!(f, "general"),
        }
    }
}

impl std::str::FromStr for BrainType {
    type Err = String;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        match s.to_ascii_lowercase().as_str() {
            "coding" => Ok(Self::Coding),
            "design" => Ok(Self::Design),
            "general" => Ok(Self::General),
            other => Err(format!("Unknown brain type: {other}")),
        }
    }
}


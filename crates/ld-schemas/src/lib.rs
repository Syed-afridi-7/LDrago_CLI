/// Invocations generated by the model during a turn.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ToolCall {
    pub id: String,
    pub name: String,
    pub arguments: String,
}

impl ToolCall {
    pub fn new(id: impl Into<String>, name: impl Into<String>, arguments: impl Into<String>) -> Self {
        Self {
            id: id.into(),
            name: name.into(),
            arguments: arguments.into(),
        }
    }
}

/// A single conversational interaction turn in a session.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Turn {
    pub role: Role,
    pub content: String,
    #[serde(default)]
    pub tool_calls: Vec<ToolCall>,
    pub timestamp: String,
}

impl Turn {
    pub fn new(role: Role, content: impl Into<String>) -> Self {
        Self {
            role,
            content: content.into(),
            tool_calls: Vec::new(),
            timestamp: chrono::Utc::now().to_rfc3339(),
        }
    }

    pub fn with_timestamp(role: Role, content: impl Into<String>, timestamp: impl Into<String>) -> Self {
        Self {
            role,
            content: content.into(),
            tool_calls: Vec::new(),
            timestamp: timestamp.into(),
        }
    }
}

/// Privacy and security boundaries for model execution.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum PrivacyClass {
    #[serde(alias = "Local", alias = "LOCAL")]
    Local,
    #[serde(alias = "RemoteApproved", alias = "remote_approved", alias = "remoteApproved")]
    RemoteApproved,
    #[serde(alias = "RemoteUnapproved", alias = "remote_unapproved", alias = "remoteUnapproved")]
    RemoteUnapproved,
}

impl std::fmt::Display for PrivacyClass {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Local => write!(f, "local"),
            Self::RemoteApproved => write!(f, "remote_approved"),
            Self::RemoteUnapproved => write!(f, "remote_unapproved"),
        }
    }
}

impl std::str::FromStr for PrivacyClass {
    type Err = String;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        match s.to_ascii_lowercase().replace('-', "_").as_str() {
            "local" => Ok(Self::Local),
            "remote_approved" | "remoteapproved" => Ok(Self::RemoteApproved),
            "remote_unapproved" | "remoteunapproved" => Ok(Self::RemoteUnapproved),
            other => Err(format!("Unknown privacy class: {other}")),
        }
    }
}

